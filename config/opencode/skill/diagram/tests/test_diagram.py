"""Tests for the diagram script.

The tests cover the parts that carry the risk. The brand theme comes from a
generated upstream artifact, and three properties of that artifact break a
naive pipeline: a comment before the opening fence, a fence inside the theme
CSS, and class definitions that only apply to a flowchart. The C4 family also
leaks its own palette, and the render needs a browser that the system does not
always provide.

The tests that need a network or a browser are marked as skipped when the
environment cannot provide one. The tests that need neither always run.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
SCRIPTS = SKILL / "scripts"

sys.path.insert(0, str(SCRIPTS))

import diagram  # noqa: E402


FRONTMATTER_SAMPLE = """# Generated by build-brand-theme-artifact.mjs. Do not edit directly.
---
config:
  theme: "base"
  themeCSS: "a{b:c}---d{e:f}"
  c4:
    diagramMarginX: 24
    system_border_color: "#000000"
---
flowchart LR
  a[A] --> b[B]
"""

FLOWCHART_SAMPLE = """%% Generated by build-brand-theme-artifact.mjs. Do not edit directly.
classDef leaf fill:#F3F3F3,stroke:#000000,stroke-width:1px,color:#000000
classDef panel fill:transparent,stroke:#000000,stroke-width:1px,color:#000000
linkStyle default stroke:#E95420,stroke-width:1px,color:#666666
"""


class FrontmatterTest(unittest.TestCase):
    def test_it_drops_the_notice_before_the_opening_fence(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        self.assertTrue(frontmatter.startswith("---\n"))
        self.assertFalse(frontmatter.startswith("#"))

    def test_it_finds_the_closing_fence_on_a_whole_line(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        self.assertIn('themeCSS: "a{b:c}---d{e:f}"', frontmatter)
        self.assertTrue(frontmatter.rstrip().endswith("---"))

    def test_it_keeps_the_c4_block(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        self.assertIn("system_border_color", frontmatter)

    def test_it_refuses_an_artifact_without_a_fence(self):
        with self.assertRaises(diagram.DiagramError):
            diagram.extract_frontmatter("no fence here\n")

    def test_it_adds_the_missing_c4_fills(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        filled = diagram.apply_c4_palette(frontmatter)
        self.assertIn("system_bg_color: #FFFFFF", filled)
        self.assertIn("person_bg_color: #FFFFFF", filled)

    def test_it_keeps_the_c4_fills_inside_the_c4_block(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        filled = diagram.apply_c4_palette(frontmatter)
        block = []
        inside = False
        for line in filled.splitlines():
            if line == "  c4:":
                inside = True
                continue
            if inside:
                if not line.startswith("    "):
                    break
                block.append(line)
        self.assertIn("    system_bg_color: #FFFFFF", block)
        self.assertNotIn("system_bg_color", frontmatter)

    def test_it_leaves_a_theme_that_already_has_the_fills(self):
        frontmatter = diagram.extract_frontmatter(FRONTMATTER_SAMPLE)
        filled = diagram.apply_c4_palette(frontmatter)
        again = diagram.apply_c4_palette(filled)
        self.assertEqual(
            filled.count("system_bg_color"), again.count("system_bg_color")
        )


class ClassDefsTest(unittest.TestCase):
    def test_it_keeps_the_class_definitions_and_the_link_style(self):
        class_defs = diagram.flowchart_class_defs(FLOWCHART_SAMPLE)
