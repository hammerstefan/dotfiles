class ChromeTest(unittest.TestCase):
    def test_it_prefers_the_puppeteer_cache_over_a_system_browser(self):
        found = diagram.find_chrome()
        if found is None:
            self.skipTest("no browser is available")
        self.assertTrue(Path(found).is_file())

    def test_it_honours_the_environment_override(self):
        with tempfile.TemporaryDirectory() as work:
            script = Path(work) / "fake-chrome"
            script.write_text("#!/bin/sh\n")
            script.chmod(0o755)
            previous = diagram.os.environ.get("PUPPETEER_EXECUTABLE_PATH")
            diagram.os.environ["PUPPETEER_EXECUTABLE_PATH"] = str(script)
            try:
                self.assertEqual(diagram.find_chrome(), str(script))
            finally:
                if previous is None:
                    diagram.os.environ.pop("PUPPETEER_EXECUTABLE_PATH", None)
                else:
                    diagram.os.environ["PUPPETEER_EXECUTABLE_PATH"] = previous


class CacheTest(unittest.TestCase):
    def test_it_falls_back_to_the_cache_when_the_fetch_fails(self):
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            (root / "artifact.yaml").write_text("cached text", encoding="utf-8")
            previous = diagram.cache_dir
            original = diagram._fetch_with_gh
            diagram.cache_dir = lambda: root
            diagram._fetch_with_gh = lambda name: (_ for _ in ()).throw(
                diagram.DiagramError("no access")
            )
            try:
                text, was_cached = diagram.fetch_artifact("artifact.yaml")
                self.assertEqual(text, "cached text")
                self.assertTrue(was_cached)
            finally:
                diagram.cache_dir = previous
                diagram._fetch_with_gh = original

    def test_it_fails_when_the_fetch_fails_and_the_cache_is_empty(self):
        with tempfile.TemporaryDirectory() as work:
            previous = diagram.cache_dir
            diagram.cache_dir = lambda: Path(work)
            original = diagram._fetch_with_gh
            diagram._fetch_with_gh = lambda name: (_ for _ in ()).throw(
                diagram.DiagramError("no access")
            )
            try:
                with self.assertRaises(diagram.DiagramError):
                    diagram.fetch_artifact("missing.yaml")
            finally:
                diagram.cache_dir = previous
                diagram._fetch_with_gh = original


@unittest.skipUnless(
    shutil.which("mmdc") and shutil.which("gh"), "mmdc and gh are required"
)
class RenderTest(unittest.TestCase):
    """Tests that render a diagram.

    The tests need the GitHub CLI, the Mermaid CLI, and a browser. They fail
    on a machine that has none of them, because they check the real output.
    """

    def test_it_renders_a_flowchart_with_the_brand_roles(self):
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            source = root / "flow.mmd"
            source.write_text(
                "flowchart LR\n  a[Alpha]:::leaf --> b[Beta]:::leaf\n",
                encoding="utf-8",
            )
            result = diagram.run(source, "flow", root / "out", True, True)
            self.assertEqual(result["family"], "flowchart")

            svg = (root / "out" / "flow.svg").read_text(encoding="utf-8")
            self.assertIn("node default leaf", svg)
            self.assertIn("#E95420", svg)
            self.assertEqual(diagram.check_brand(svg, "flowchart"), [])

            html = (root / "out" / "flow.html").read_text(encoding="utf-8")
            self.assertIn("mermaid.initialize", html)
            self.assertIn("mermaid.min.js", html)

    def test_it_renders_a_c4_diagram_without_off_brand_colours(self):
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            source = root / "c4.mmd"
            source.write_text(
                'C4Context\n  Person(u, "User", "")\n  System(s, "System", "")\n'
                '  Rel(u, s, "Uses")\n',
                encoding="utf-8",
            )
            result = diagram.run(source, "c4", root / "out", False, False)
            self.assertEqual(result["family"], "c4")

            svg = (root / "out" / "c4.svg").read_text(encoding="utf-8")
            self.assertNotIn("#1168BD", svg)
            self.assertEqual(diagram.check_brand(svg, "c4"), [])

    def test_it_writes_nothing_when_the_brand_check_fails(self):
        with tempfile.TemporaryDirectory() as work:
            root = Path(work)
            source = root / "bad.mmd"
            source.write_text("flowchart LR\n  a --> b\n", encoding="utf-8")

            original = diagram.check_brand
            diagram.check_brand = lambda svg, family: ["forced failure"]
            try:
                with self.assertRaises(diagram.DiagramError):
                    diagram.run(source, "bad", root / "out", True, True)
            finally:
                diagram.check_brand = original

            self.assertFalse((root / "out" / "bad.svg").exists())
            self.assertFalse((root / "out" / "bad.mmd").exists())


